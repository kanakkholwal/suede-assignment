import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../components/icons');
const OUT = join(ROOT, 'generated.ts');
const check = process.argv.includes('--check');
const require = createRequire(import.meta.url);
const SOLAR = JSON.parse(readFileSync(require.resolve('@iconify-json/solar/icons.json'), 'utf8'));

function entry(ref) {
  const [set, name] = ref.split(':');
  const icon = set === 'solar' ? SOLAR.icons[name] : undefined;
  if (!icon) throw new Error(`icons.json: no icon for "${ref}"`);
  const width = icon.width ?? SOLAR.width ?? 24;
  const height = icon.height ?? SOLAR.height ?? 24;
  return { viewBox: `0 0 ${width} ${height}`, body: icon.body.replace(/\s*\n\s*/g, '').trim() };
}

const manifest = JSON.parse(readFileSync(join(ROOT, 'icons.json'), 'utf8'));
const names = Object.keys(manifest).sort();
const text = [
  '// Generated by scripts/generate-icons.mjs from icons.json (Solar, CC BY 4.0). Do not edit.',
  'export const ICONS = {',
  ...names.map((name) => `  ${name}: ${JSON.stringify(entry(manifest[name]))},`),
  '} as const;',
  '',
].join('\n');

let current = '';
try {
  current = readFileSync(OUT, 'utf8');
} catch {}

if (check) {
  if (current !== text) {
    console.error('icons: generated.ts is stale, run `pnpm icons`');
    process.exit(1);
  }
  console.log(`icons: ${names.length} up to date`);
} else {
  if (current !== text) writeFileSync(OUT, text);
  console.log(`icons: ${names.length} icons${current === text ? ', unchanged' : ' written'}`);
}
